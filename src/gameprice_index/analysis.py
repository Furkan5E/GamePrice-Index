"""Turns the dataset into a short written report of what the prices show."""

import logging

import pandas as pd

from gameprice_index.matching import cross_store_prices, store_comparison
from gameprice_index.visualiser import sources_in

logger = logging.getLogger(__name__)

MIN_GAMES_TO_REPORT = 20  # storefronts with fewer games are listed but not compared
FULL_PRICE_THRESHOLD = 50  # pounds; roughly where new big-budget releases start
TOP_GAPS = 10


def storefront_summary(df: pd.DataFrame) -> pd.DataFrame:
    """One row per storefront: catalogue size, typical price and how much of it is discounted."""
    rows = []
    for source in sources_in(df):
        games = df[df["source"] == source]
        priced = games.dropna(subset=["price"])
        on_sale = priced.dropna(subset=["discount_pct"])
        rows.append(
            {
                "source": source,
                "games": len(games),
                "median_price": round(float(priced["price"].median()), 2) if not priced.empty else None,
                "mean_price": round(float(priced["price"].mean()), 2) if not priced.empty else None,
                "free_pct": round(float((priced["price"] == 0).mean() * 100), 1) if not priced.empty else None,
                "full_price_pct": round(float((priced["price"] >= FULL_PRICE_THRESHOLD).mean() * 100), 1)
                if not priced.empty
                else None,
                "on_sale_pct": round(len(on_sale) / len(priced) * 100, 1) if not priced.empty else None,
                "median_discount_pct": round(float(on_sale["discount_pct"].median()), 1) if not on_sale.empty else None,
            }
        )
    return pd.DataFrame(rows)


def platform_summary(df: pd.DataFrame) -> pd.DataFrame:
    """Median price per platform, for platforms with enough games to say something."""
    priced = df.dropna(subset=["price"])
    summary = (
        priced.groupby(["source", "platform"])["price"]
        .agg(games="size", median_price="median")
        .reset_index()
        .query("games >= @MIN_GAMES_TO_REPORT")
        .sort_values("median_price", ascending=False)
    )
    summary["median_price"] = summary["median_price"].round(2)
    return summary.reset_index(drop=True)


def _table(df: pd.DataFrame, columns: dict[str, str]) -> str:
    """Renders selected columns as a Markdown table, with missing values as a dash."""
    header = "| " + " | ".join(columns.values()) + " |"
    divider = "| " + " | ".join("---" for _ in columns) + " |"
    lines = [header, divider]
    for row in df.to_dict("records"):
        cells = []
        for column in columns:
            value = row[column]
            if value is None or (isinstance(value, float) and value != value):
                cells.append("-")
            elif isinstance(value, float):
                cells.append(f"{value:g}" if column.endswith("_pct") else f"{value:,.2f}")
            else:
                cells.append(f"{value:,}" if isinstance(value, int) else str(value).replace("|", "/"))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def build_report(df: pd.DataFrame) -> str:
    """Writes the findings as Markdown. Every number is computed from `df`; nothing is hard-coded."""
    stores = storefront_summary(df)
    comparable = stores[stores["games"] >= MIN_GAMES_TO_REPORT]
    matched = cross_store_prices(df)
    comparison = store_comparison(matched, sources_in(df))
    comparison = comparison[comparison["shared_games"] >= MIN_GAMES_TO_REPORT]

    lines = [
        "# Findings",
        "",
        f"{len(df):,} games from {len(stores)} UK storefronts. "
        "Generated by `gameprice-index report`; rerun it after a scrape to refresh every number.",
        "",
        "## Storefronts at a glance",
        "",
        _table(
            stores,
            {
                "source": "Storefront",
                "games": "Games",
                "median_price": "Median price (£)",
                "mean_price": "Mean price (£)",
                "free_pct": "Free (%)",
                "full_price_pct": f"£{FULL_PRICE_THRESHOLD}+ (%)",
                "on_sale_pct": "On sale (%)",
                "median_discount_pct": "Median discount (%)",
            },
        ),
        "",
    ]

    if not comparable.empty:
        cheapest = comparable.loc[comparable["median_price"].idxmin()]
        dearest = comparable.loc[comparable["median_price"].idxmax()]
        most_sales = comparable.loc[comparable["on_sale_pct"].idxmax()]
        deepest = comparable.dropna(subset=["median_discount_pct"])
        lines += [
            f"- **{cheapest['source']}** has the lowest median price (£{cheapest['median_price']:.2f}) and "
            f"**{dearest['source']}** the highest (£{dearest['median_price']:.2f}).",
            f"- **{most_sales['source']}** has the largest share of its catalogue on sale "
            f"({most_sales['on_sale_pct']:g}%).",
        ]
        if not deepest.empty:
            deepest_row = deepest.loc[deepest["median_discount_pct"].idxmax()]
            lines.append(
                f"- Discounts run deepest on **{deepest_row['source']}**, where the typical sale takes "
                f"{deepest_row['median_discount_pct']:g}% off."
            )
        small = stores[stores["games"] < MIN_GAMES_TO_REPORT]["source"].tolist()
        if small:
            lines.append(
                f"- {', '.join(small)} lists fewer than {MIN_GAMES_TO_REPORT} games and is left out of the comparisons."
            )
        lines.append("")

    lines += ["## The same game on different stores", ""]
    if comparison.empty:
        lines += ["No game is sold on more than one of the scraped storefronts.", ""]
    else:
        lines += [
            f"{len(matched):,} games were matched on at least two storefronts by normalised title. "
            "Regular prices are compared, so a temporary sale on one store does not count as that store being cheaper.",
            "",
            _table(
                comparison,
                {
                    "source": "Storefront",
                    "shared_games": "Shared games",
                    "median_price": "Median price (£)",
                    "median_price_elsewhere": "Median price elsewhere (£)",
                    "mean_difference_pct": "Average difference (%)",
                    "cheapest_share_pct": "Cheapest or tied (%)",
                },
            ),
            "",
        ]
        low = comparison.loc[comparison["mean_difference_pct"].idxmin()]
        high = comparison.loc[comparison["mean_difference_pct"].idxmax()]
        lines += [
            f"- On shared games **{low['source']}** averages {low['mean_difference_pct']:+g}% against the other stores "
            f"and **{high['source']}** {high['mean_difference_pct']:+g}%.",
            "- Most multi-platform games cost the same everywhere; the gaps come from a minority of titles.",
            "",
            f"### Largest regular-price gaps (top {TOP_GAPS})",
            "",
        ]
        gaps = matched.sort_values("spread", ascending=False).head(TOP_GAPS)
        # a store with none of these games would only add an empty column
        store_columns = {store: store for store in sources_in(df) if store in gaps and gaps[store].notna().any()}
        lines += [_table(gaps, {"name": "Game", **store_columns, "spread": "Gap (£)"}), ""]

    platforms = platform_summary(df)
    if not platforms.empty:
        lines += [
            "## Platforms",
            "",
            _table(
                platforms,
                {"platform": "Platform", "source": "Storefront", "games": "Games", "median_price": "Median price (£)"},
            ),
            "",
        ]

    lines += [
        "## How to read this",
        "",
        "- Each storefront contributes its most popular games (1,000 by default), not its whole catalogue.",
        "- Prices are UK prices in pounds, as listed on the day of the scrape.",
        "- Title matching is deliberately strict: sequels, remasters and special editions count as different games.",
        "",
    ]
    return "\n".join(lines)
